"""Generate src/core/ObviousPairs.h from effects.csv's obvious_needs column.

    python -I tools/effects/make_obvious_pairs.py           # write ObviousPairs.h and the doc's table
    python -I tools/effects/make_obvious_pairs.py --check   # exit 1 if either is stale

The obvious need x effect pairs (doc 9, "Pairs") are the pairs whose theta starts
away from the dense prior: fitlib.obvious_pairs reads them from effects.csv for the
offline fit, and the R8 bootstrap reader (core/Bootstrap.h) needs the same list in the
plugin to give a pair the file lacks its prior (docs/architecture/9-bootstrap-format.md,
Names). The sign rule is fitlib's: +1, except a need written "-need" (0.24.33) and
combat_regen_ok x kind_food (-1), and every
overshoot_* column (0: the logged overshoot is signed and not curved).
tests/core/ObviousPairsTests.cpp checks the header against the csv on every build.

It also writes the full table of pairs into docs/architecture/9-hand-tuned.md,
between the BEGIN / END obvious-pairs markers, grouped by effect family; --check
fails when that table is stale too (the doc's only guard: no test reads it).
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EFFECTS = os.path.join(ROOT, "docs", "architecture", "9-data", "effects.csv")
NEEDS = os.path.join(ROOT, "docs", "architecture", "9-data", "needs.csv")
HEADER = os.path.join(ROOT, "src", "core", "ObviousPairs.h")
DOC = os.path.join(ROOT, "docs", "architecture", "9-hand-tuned.md")
DOC_BEGIN = "<!-- BEGIN obvious-pairs: generated by tools/effects/make_obvious_pairs.py from effects.csv; do not edit by hand -->"
DOC_END = "<!-- END obvious-pairs -->"
LEVEL_GROUPS = {   # effects.csv levels without a family, in the table's order
    "modifier": "Modifiers",
    "item_feature": "Item features",
    "weapon_stat": "Weapon stats",
    "armour_stat": "Armour stats",
}


def pairs():
    with open(NEEDS, encoding="utf-8", newline="") as f:
        needs = [r["id"] for r in csv.DictReader(f)]
    out = []
    with open(EFFECTS, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            for t in r["obvious_needs"].split(";"):
                t = t.strip()
                if not t:
                    continue
                neg = t.startswith("-")   # 0.24.33: "-need" is a negative pair
                t = t.lstrip("-").strip()
                if t not in needs:
                    raise SystemExit(f"effects.csv {r['id']}: obvious need {t!r} is not in needs.csv")
                sign = -1 if neg or (t == "combat_regen_ok" and r["id"] == "kind_food") else 1
                if r["id"].startswith("overshoot_"):
                    sign = 0
                out.append((r["id"], t, sign))
    return out


def make_doc_table(ps):
    """The markdown table of every pair, one row per effect column, grouped by
    family (a family column with its specifics), then the levels without one."""
    with open(EFFECTS, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    by_col = {}
    for c, n, s in ps:
        by_col.setdefault(c, []).append((n, s))
    groups, order = {}, []
    for r in rows:
        if r["id"] not in by_col:
            continue
        g = r["id"] if r["level"] == "family" else (r["family"] or LEVEL_GROUPS.get(r["level"], r["level"]))
        if g not in groups:
            groups[g] = []
            order.append(g)
        if r["id"] not in groups[g]:
            groups[g].append(r["id"])
    fams = [g for g in order if g not in LEVEL_GROUPS.values()]
    rest = [g for g in LEVEL_GROUPS.values() if g in groups]
    w = [DOC_BEGIN, "",
         f"{len(ps)} pairs on {len(by_col)} effect columns. +1 starts the weight at +1, -1 at -1 "
         "(written `-need` in effects.csv), 0 at 0 with the obvious pair's wider prior (sigma 1).", ""]
    for g in fams + rest:
        w.append(f"**{g}**" if g in rest else f"**{g}** (family)")
        w.append("")
        w.append("| Column | +1 | -1 | 0 |")
        w.append("|---|---|---|---|")
        for c in groups[g]:
            def cell(sg):
                return ", ".join(f"`{n}`" for n, s in by_col[c] if s == sg)
            w.append(f"| `{c}` | {cell(1)} | {cell(-1)} | {cell(0)} |")
        w.append("")
    w.append(DOC_END)
    return "\n".join(w)


def doc_with_table(cur, table):
    """`cur` with its BEGIN..END block replaced by `table`; None when the markers are missing."""
    i, j = cur.find(DOC_BEGIN), cur.find(DOC_END)
    if i < 0 or j < i:
        return None
    return cur[:i] + table + cur[j + len(DOC_END):]


def make_header(ps):
    w = []
    w.append("#pragma once")
    w.append("")
    w.append("// =============================================================================")
    w.append(f"// OBVIOUS PAIRS -- the {len(ps)} obvious need x effect pairs of effects.csv")
    w.append("// =============================================================================")
    w.append("// GENERATED by tools/effects/make_obvious_pairs.py from")
    w.append("// docs/architecture/9-data/effects.csv (obvious_needs); do not edit by hand.")
    w.append("// tests/core/ObviousPairsTests.cpp fails if the two drift apart.")
    w.append("//")
    w.append("// The pairs whose theta starts away from the dense prior (doc 9, \"Pairs\";")
    w.append("// fitlib.obvious_pairs): theta0 = sign (the prior's T0 = 1), sigma = 1 (precision")
    w.append("// 1). Every other pair starts at 0 with sigma 0.3 (precision 11.1111). The R8")
    w.append("// bootstrap reader gives a pair the file lacks this prior (core/Bootstrap.h).")
    w.append("// Sign: +1; -1 for a need effects.csv writes \"-need\" (0.24.33) and for")
    w.append("// combat_regen_ok x kind_food; 0 for the overshoot_* columns.")
    w.append("//")
    w.append("// Pure: standard library only (src/core/README.md).")
    w.append("// =============================================================================")
    w.append("")
    w.append('#include "core/EffectColumns.h"')
    w.append('#include "core/NeedIds.h"')
    w.append("")
    w.append("#include <array>")
    w.append("#include <cstddef>")
    w.append("#include <cstdint>")
    w.append("")
    w.append("namespace Huginn::Core::Obvious")
    w.append("{")
    w.append("    struct Pair")
    w.append("    {")
    w.append("        Effect::Col col;")
    w.append("        Needs::NeedId need;")
    w.append("        std::int8_t sign;   // theta0 / T0: +1, -1 or 0")
    w.append("    };")
    w.append("")
    w.append(f"    inline constexpr std::size_t kPairCount = {len(ps)};")
    w.append("")
    w.append("    inline constexpr std::array<Pair, kPairCount> kPairs{ {")
    for c, n, s in ps:
        w.append(f"        {{ Effect::Col::{c}, Needs::NeedId::{n}, {s} }},")
    w.append("    } };")
    w.append("")
    w.append("    /// The prior centre's sign of (need, col): 1, -1 or 0 for an obvious pair;")
    w.append("    /// `isObvious` false (and 0) otherwise.")
    w.append("    struct Prior")
    w.append("    {")
    w.append("        bool isObvious = false;")
    w.append("        std::int8_t sign = 0;")
    w.append("    };")
    w.append("")
    w.append("    [[nodiscard]] constexpr Prior PriorOf(Needs::NeedId need, Effect::Col col) noexcept")
    w.append("    {")
    w.append("        for (const auto& p : kPairs) {")
    w.append("            if (p.need == need && p.col == col) return Prior{ true, p.sign };")
    w.append("        }")
    w.append("        return Prior{};")
    w.append("    }")
    w.append("}")
    w.append("")
    return "\n".join(w)


def main(argv):
    if argv not in ([], ["--check"]):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    ps = pairs()
    text = make_header(ps)
    try:
        with open(DOC, encoding="utf-8", newline="") as f:
            doc_cur = f.read().replace("\r\n", "\n")
    except OSError:
        doc_cur = None
    doc_new = doc_with_table(doc_cur, make_doc_table(ps)) if doc_cur is not None else None
    if doc_new is None:
        print(f"{DOC}: missing, or without the obvious-pairs markers", file=sys.stderr)
        return 1
    if argv == ["--check"]:
        try:
            with open(HEADER, encoding="utf-8", newline="") as f:
                cur = f.read()
        except OSError:
            cur = None
        stale = False
        if cur != text:
            print(f"{HEADER} is stale: run python -I tools/effects/make_obvious_pairs.py", file=sys.stderr)
            stale = True
        if doc_cur != doc_new:
            print(f"{DOC}'s pair table is stale: run python -I tools/effects/make_obvious_pairs.py", file=sys.stderr)
            stale = True
        if stale:
            return 1
        print("ObviousPairs.h and the hand-tuned doc's pair table are up to date")
        return 0
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    with open(DOC, "w", encoding="utf-8", newline="\n") as f:
        f.write(doc_new)
    print(f"wrote {HEADER} and {DOC}'s pair table")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
